"""Tests for the reproducible offline synthetic evaluation harness.

These assert four things:

1. **Determinism** — two runs produce identical measured numbers (timings aside),
   so a stored report can be regenerated byte-for-byte.
2. **Privacy negative tests** — the runner and the report must never carry raw
   identifiers, secrets, or provider payloads, and the fake provider must make no
   network call.
3. **Measurement honesty** — unavailable metrics are marked unavailable rather
   than reported as zero/None, and no live-service metric is claimed.
4. **Safety gates** — escalations are never hidden, a stranger is not collapsed
   into another principal's repeat, the queue drops without blocking, and the
   dedup registry is bounded.

Plus the **rollback gate**: with dedup disabled (the documented kill switch) every
event reaches the provider and nothing is suppressed, so rollback is provable.
"""

import json
import unittest

from auth_audit_jev import DedupLayer
from auth_audit_jev.evaluation import (
    CORPUS,
    EVALUATION_VERSION,
    NOT_MEASURED,
    SyntheticProvider,
    report_to_json,
    run_evaluation_sync,
)
from auth_audit_jev.fixtures import SCRUB_TOKENS


# Metric keys that carry wall-clock observations and therefore legitimately vary
# run to run. Everything else must be bit-identical.
_VOLATILE_METRIC_KEYS = (
    "provider_latency_sum_seconds",
    "provider_latency_max_seconds",
    "latency_sum_seconds",
    "latency_max_seconds",
)


def _strip_volatile(payload):
    snapshot = dict(payload.get("metrics_snapshot") or {})
    for key in list(snapshot):
        if key.lower() in _VOLATILE_METRIC_KEYS:
            snapshot.pop(key)
    payload = dict(payload)
    payload["metrics_snapshot"] = snapshot
    probe = dict(payload.get("queue_pressure") or {})
    probe.pop("max_emit_seconds", None)  # measured wall-clock observation
    payload["queue_pressure"] = probe
    return payload


def _stable(report):
    """Report fields that must be identical across runs (wall-clock + seed excluded).

    ``seed`` is recorded rather than acted on, so it is excluded from the
    comparison of measurements; a separate assertion checks it is echoed back.
    """
    payload = _strip_volatile(report.__dict__.copy())
    payload.pop("offline_latency", None)  # wall-clock; observed-not-guaranteed
    payload.pop("seed", None)             # recorded, not a measurement
    return json.dumps(payload, sort_keys=True, default=str)


class DeterminismTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.first = run_evaluation_sync(seed=0)
        cls.second = run_evaluation_sync(seed=0)

    def test_two_runs_are_byte_identical_except_timings(self):
        self.assertEqual(_stable(self.first), _stable(self.second))

    def test_version_is_pinned(self):
        self.assertEqual(self.first.version, EVALUATION_VERSION)

    def test_corpus_is_fixed_and_enumerated(self):
        names = [s.name for s in CORPUS]
        self.assertEqual(len(names), len(set(names)), "scenario names must be unique")
        self.assertGreaterEqual(len(CORPUS), 15)

    def test_seed_does_not_change_a_fixed_corpus(self):
        # The corpus is fixed, so the seed may change only the recorded seed itself.
        # Every measured value must be identical.
        varying = run_evaluation_sync(seed=99)
        self.assertEqual(_stable(self.first), _stable(varying))
        self.assertEqual(varying.seed, 99)
        self.assertNotEqual(self.first.seed, varying.seed)


class MeasurementHonestyTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.report = run_evaluation_sync(seed=0)

    def test_unavailable_metrics_are_marked_and_not_measured(self):
        for key in ("live_jev_confidence", "event_to_alert_latency"):
            self.assertIn(key, self.report.not_measured)
            self.assertIn("no ", self.report.not_measured[key].lower())
            self.assertEqual(self.report.not_measured[key], NOT_MEASURED[key])

    def test_report_declares_itself_a_simulation(self):
        self.assertTrue(self.report.simulated)
        blob = report_to_json(self.report)
        self.assertIn("SIMULATION", blob.upper())

    def test_latency_is_labeled_not_production_p99(self):
        self.assertIn("NOT", self.report.offline_latency["note"])

    def test_provider_cost_is_marked_unavailable(self):
        self.assertIn("provider_cost_usd", self.report.not_measured)


class PrivacyNegativeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.report = run_evaluation_sync(seed=0)
        cls.blob = report_to_json(cls.report)

    def test_report_contains_no_scrub_tokens_or_secret_markers(self):
        for secret in SCRUB_TOKENS:
            self.assertNotIn(secret, self.blob, secret)
        # The report must not carry the raw marker prefix in any form.
        self.assertNotIn("SECRET", self.blob)

    def test_report_contains_no_corpus_scope_or_principal_values(self):
        # The corpus uses these literal scope values only to key the local dedup
        # fingerprint. None may leak into the report.
        for token in ("alpha", "bravo", "charlie", "different-user",
                      "principal-99", "unregistered-client"):
            self.assertNotIn(token, self.blob, token)

    def test_report_carries_no_provider_payload_or_authorization_header(self):
        for token in ("Authorization", "Bearer", "api_key", "answers",
                      "probabilities", "jev-evil"):
            self.assertNotIn(token, self.blob, token)

    def test_metric_labels_are_from_closed_enums_only(self):
        for label in self.report.metrics_snapshot["results"]:
            self.assertIsInstance(label, str)
            self.assertNotIn("SECRET", label)

    def test_fake_provider_is_pure_and_raises_on_unknown_signal(self):
        # A request whose signal is not in the declared corpus must fail loudly
        # rather than fall through to a network call.
        provider = SyntheticProvider({})
        self.assertEqual(provider.calls, [])
        with self.assertRaises(AssertionError):
            provider.response_for({"state": {"signal": {"unknown": True}}})
        self.assertEqual(provider.calls, [], "response_for must not record a call")


class GateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.report = run_evaluation_sync(seed=0)

    def test_no_escalation_is_hidden(self):
        self.assertEqual(self.report.escalations_hidden, [])
        self.assertEqual(self.report.escalations_evaluated,
                         self.report.escalations_must_evaluate)
        self.assertGreater(self.report.escalations_must_evaluate, 0)

    def test_dedup_saves_provider_calls_but_not_safety(self):
        self.assertGreaterEqual(self.report.provider_calls_saved, 2)
        self.assertLess(self.report.provider_calls_dedup,
                        self.report.provider_calls_baseline)

    def test_observed_call_and_suppression_counts_reconcile(self):
        verdicts = self.report.scenario_verdicts
        self.assertEqual(self.report.provider_calls_dedup,
                         sum(v["evaluated"] for v in verdicts))
        self.assertEqual(self.report.metrics_snapshot["provider_calls"],
                         self.report.provider_calls_dedup)
        self.assertEqual(self.report.dedup_counters["suppressed"],
                         sum(v["suppressed"] for v in verdicts))
        self.assertEqual(self.report.no_alert_outcomes,
                         sum(v["observed"] is None for v in verdicts))

    def test_stranger_is_not_collapsed_into_another_principals_repeat(self):
        verdict = next(v for v in self.report.scenario_verdicts
                       if v["name"] == "stranger_same_signal_new_principal")
        self.assertTrue(verdict["evaluated"])
        self.assertFalse(verdict["suppressed"])

    def test_repeat_group_is_suppressed(self):
        suppressed = [v for v in self.report.scenario_verdicts if v["suppressed"]]
        self.assertTrue(suppressed, "at least one exact repeat must be suppressed")
        for verdict in suppressed:
            self.assertFalse(verdict["evaluated"])

    def test_queue_drops_without_blocking_and_is_counted(self):
        self.assertGreater(self.report.queue_pressure["queue_drops"], 0)
        self.assertTrue(self.report.queue_pressure["emit_never_blocked"])

    def test_dedup_state_is_bounded(self):
        bounds = self.report.state_bounds
        self.assertTrue(bounds["bounded"])
        self.assertLessEqual(bounds["final_size"], bounds["capacity"])
        self.assertGreater(bounds["evicted"], 0)

    def test_abstains_are_present_and_never_alerts(self):
        self.assertGreaterEqual(self.report.abstains, 2)
        for verdict in self.report.scenario_verdicts:
            if verdict["observed"] is None:
                self.assertTrue(verdict["suppressed"] or verdict["evaluated"])

    def test_false_positive_and_negative_traps_are_detected_by_harness(self):
        # The harness must be able to observe a wrong provider answer at all,
        # otherwise a zero FP/FN count would be meaningless.
        self.assertGreaterEqual(self.report.false_positives, 1)
        self.assertGreaterEqual(self.report.false_negatives, 1)
        self.assertIn("fp_trap_provider_says_abuse_on_stale_secret",
                      self.report.false_positive_events[0])
        self.assertIn("fn_trap_provider_says_user_error_on_spray",
                      self.report.false_negative_events)


class RollbackGateTests(unittest.TestCase):
    """The kill switch must restore the baseline path completely."""

    def test_dedup_disabled_evaluates_every_scenario(self):
        report = run_evaluation_sync(seed=0, dedup_enabled=False)
        self.assertEqual(report.provider_calls_dedup, report.provider_calls_baseline)
        self.assertEqual(report.provider_calls_saved, 0)
        self.assertTrue(all(v["evaluated"] for v in report.scenario_verdicts))
        self.assertFalse(any(v["suppressed"] for v in report.scenario_verdicts))

    def test_kill_switch_is_the_documented_rollback(self):
        layer = DedupLayer(capacity=4, ttl_seconds=300.0)
        signal = {
            "protocol": "oauth2", "flow": "authorization_code",
            "failure_reason": "invalid_credentials", "client_config_category": "none",
            "authz_denial_category": None, "outcome": "failure",
            "repeat_pattern": "not_repeated", "count_bucket": "1",
            "window_bucket": "under-1m",
        }
        layer.decide(signal, tenant="t1", context={"principal": "p"}, now=0.0)
        self.assertEqual(layer.decide(signal, tenant="t1", context={"principal": "p"},
                                      now=1.0), "suppress")
        layer.engage_kill_switch()
        self.assertEqual(layer.decide(signal, tenant="t1", context={"principal": "p"},
                                      now=2.0), "evaluate")


if __name__ == "__main__":
    unittest.main()
